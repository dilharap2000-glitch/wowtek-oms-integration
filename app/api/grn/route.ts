import { NextResponse } from 'next/server';
import { connectToDatabase } from '@/lib/mongodb';
import { ObjectId } from 'mongodb';

export const dynamic = 'force-dynamic';

export async function POST(req: Request) {
  try {
    const body = await req.json();
    const { sku, restockQty, costPrice, sellingPrice, supplier, batchRef, serialNumbersInput } = body;

    const rawSku = String(sku || body.skuCode || body.barcode || body.id || body.productId || '').trim();
    if (!rawSku) {
      return NextResponse.json({ success: false, message: 'No SKU or Product ID provided' }, { status: 400 });
    }

    const { db } = await connectToDatabase();
    const qty = Number(restockQty || body.qtyAdded || 1);

    if (isNaN(qty) || qty <= 0) {
      return NextResponse.json({ success: false, message: 'Invalid restock quantity' }, { status: 400 });
    }

    // 1. Serial numbers පාර්ස් කර ගැනීම (Comma separated)
    let serialsArray: string[] = [];
    if (serialNumbersInput && typeof serialNumbersInput === 'string' && serialNumbersInput.trim() !== '') {
      serialsArray = serialNumbersInput.split(',').map((s: string) => s.trim()).filter(Boolean);
    }

    const processedUnits = [];

    // 2. Quantity එකට අදාළව Serials හෝ Auto Barcodes සකස් කිරීම
    for (let i = 0; i < qty; i++) {
      const assignedSerial = serialsArray[i] || `AUTO-${rawSku}-${Math.random().toString(36).substring(2, 8).toUpperCase()}`;

      processedUnits.push({
        serialNumber: assignedSerial,
        isAutoGenerated: !serialsArray[i],
        batchRef: batchRef || `GRN-${Date.now()}`,
        costPrice: Number(costPrice || 0),
        sellingPrice: Number(sellingPrice || 0),
        status: 'In-Stock',
        addedDate: new Date(),
      });
    }

    // Determine query conditions to match product by sku, skuCode, barcode, or ObjectId
    let isObjectId = false;
    try {
      isObjectId = ObjectId.isValid(rawSku) && rawSku.length === 24;
    } catch {
      isObjectId = false;
    }

    const productQuery: any = {
      $or: [
        { sku: rawSku },
        { sku: rawSku.toUpperCase() },
        { sku: rawSku.toLowerCase() },
        { skuCode: rawSku },
        { barcode: rawSku },
        { code: rawSku },
        { _id: rawSku },
        ...(isObjectId ? [{ _id: new ObjectId(rawSku) }] : []),
      ],
    };

    const existingProduct = await db.collection<any>('products').findOne(productQuery);
    if (!existingProduct) {
      return NextResponse.json(
        { success: false, message: `Product not found for SKU: ${rawSku}` },
        { status: 404 }
      );
    }

    const targetSku = existingProduct.sku || rawSku;
    const finalCostPrice = Number(costPrice ?? existingProduct.costPrice ?? 0);
    const finalSellingPrice = Number(sellingPrice ?? existingProduct.sellingPrice ?? 0);
    const effectiveBatch = batchRef || `GRN-${Date.now()}`;
    const effectiveSupplier = supplier || existingProduct.supplier || 'Direct Supplier';

    // 3. Products collection එක update කිරීම
    await db.collection('products').updateOne(
      { _id: existingProduct._id },
      {
        $inc: {
          storeStock: qty,
          stockQuantity: qty,
          stockStore: qty,
        },
        $push: {
          activeSerials: {
            $each: processedUnits,
          },
        } as any,
        $set: {
          stockWarehouse: 0,
          lastRestockedAt: new Date(),
          lastBatchRef: effectiveBatch,
          supplier: effectiveSupplier,
          updatedAt: new Date().toISOString(),
          ...(finalCostPrice > 0 ? { costPrice: finalCostPrice } : {}),
          ...(finalSellingPrice > 0 ? { sellingPrice: finalSellingPrice } : {}),
        },
      }
    );

    // 4. Expenses වලට Cost එක එකතු කිරීම
    const totalCost = Number(finalCostPrice || 0) * qty;
    await db.collection('expenses').insertOne({
      category: 'Inventory Restock',
      description: `GRN Restock for SKU: ${targetSku} (Qty: ${qty})`,
      amount: totalCost,
      supplier: effectiveSupplier,
      batchRef: effectiveBatch,
      createdAt: new Date(),
    });

    // Also record in grns collection for audit ledger
    try {
      await db.collection('grns').insertOne({
        productId: existingProduct._id,
        sku: targetSku,
        qtyAdded: qty,
        costPrice: finalCostPrice,
        sellingPrice: finalSellingPrice,
        totalCost: totalCost,
        supplier: effectiveSupplier,
        batchRef: effectiveBatch,
        serials: processedUnits.map((u) => u.serialNumber),
        createdAt: new Date(),
      });
    } catch (e: any) {
      console.warn('[GRN API] Error inserting into grns ledger:', e?.message);
    }

    // 5. 🚀 AUTO-SETTLE PENDING ORDERS LOGIC (GRN එක දැමූ සැනින් Pending Orders ක්රියාත්මක වීම)
    const pendingOrders = await db.collection('orders').find({
      status: 'Pending Stock',
      $or: [
        { 'items.sku': targetSku },
        { 'items.skuCode': targetSku },
        { 'items.sku': rawSku },
      ],
    }).sort({ createdAt: 1 }).toArray();

    let settledCount = 0;

    for (const order of pendingOrders) {
      const updatedProduct = await db.collection<any>('products').findOne({ _id: existingProduct._id });
      const freshAvailableUnits = (updatedProduct?.activeSerials || []).filter((s: any) => s.status === 'In-Stock');

      const targetItem = (order.items || []).find((i: any) => i.sku === targetSku || i.skuCode === targetSku || i.sku === rawSku);
      const neededQty = Number(targetItem?.qty || targetItem?.quantity || 1);

      if (freshAvailableUnits.length >= neededQty) {
        const allocatedUnits = freshAvailableUnits.slice(0, neededQty);
        const unitIdsToUpdate = allocatedUnits.map((u: any) => u.serialNumber);

        // Serial status එක 'Sold' කර Store Stock එකෙන් අඩු කිරීම
        await db.collection('products').updateOne(
          { _id: updatedProduct._id, 'activeSerials.serialNumber': { $in: unitIdsToUpdate } },
          {
            $inc: { storeStock: -neededQty, stockQuantity: -neededQty, stockStore: -neededQty },
            $set: { 'activeSerials.$[elem].status': 'Sold' },
          },
          { arrayFilters: [{ 'elem.serialNumber': { $in: unitIdsToUpdate } }] }
        );

        // Order එක 'Completed' තත්වයට පත් කිරීම
        const cPrice = Number(allocatedUnits[0]?.costPrice || updatedProduct.costPrice || 0);
        const uPrice = Number(targetItem.sellingPrice || targetItem.unitPrice || updatedProduct.sellingPrice || 0);
        const itemProfit = uPrice - cPrice;

        await db.collection('orders').updateOne(
          { _id: order._id },
          {
            $set: {
              status: 'Completed',
              netProfit: itemProfit * neededQty,
              'items.$[elem].allocatedSerials': unitIdsToUpdate,
              'items.$[elem].status': 'Allocated & Sold',
              settledAt: new Date(),
            },
          },
          { arrayFilters: [{ $or: [{ 'elem.sku': targetSku }, { 'elem.skuCode': targetSku }, { 'elem.sku': rawSku }] }] }
        );

        settledCount++;
      }
    }

    const finalProductDoc = await db.collection('products').findOne({ _id: existingProduct._id });

    return NextResponse.json({
      success: true,
      message: `Successfully restocked ${qty} items! Pending orders auto-settled: ${settledCount}.`,
      units: processedUnits,
      product: finalProductDoc,
      settledOrdersCount: settledCount,
    });
  } catch (error: any) {
    console.error('GRN Error:', error);
    return NextResponse.json({ success: false, error: error.message }, { status: 500 });
  }
}
